import type { Metadata } from "next";
import "./globals.css";
import { AuthProvider } from "@/components/auth/auth-provider";
import { DetailProfileDTO } from "@/lib/type/profile";
import { profileServerApi } from "@/features/profiles/api/profile.server";
import { QueryProvider } from "@/lib/providers/query-provider";
import { ThemeProvider } from "@/lib/providers/theme-provider";

import { WebSocketProvider } from "@/components/websocket/websocket-provider";

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};




export default async function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {

  let profile: DetailProfileDTO | null = null

  try {
    profile = await profileServerApi.getMyProfile()

  } catch (_) {
  }

  return (
    <html lang="en" suppressHydrationWarning>
      <body
        className={`antialiased`}
      >
        <ThemeProvider
          attribute={"class"}
          defaultTheme="system"
          enableSystem
          disableTransitionOnChange
        >
          <AuthProvider user={profile}>
            <QueryProvider>
              <WebSocketProvider>
                {children}
              </WebSocketProvider>
            </QueryProvider>
          </AuthProvider>
        </ThemeProvider>
      </body>
    </html>
  );
}